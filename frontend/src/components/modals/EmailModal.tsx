import { Check, Copy, Download, Mail, Send } from "lucide-react";
import { useState } from "react";
import { copilotActions } from "../../store/copilotSlice";
import { useAppDispatch, useAppSelector } from "../../store/hooks";
import { uiActions } from "../../store/uiSlice";
import { Modal } from "../ui";

export default function EmailModal() {
  const dispatch = useAppDispatch();
  const { emailOpen, emailDraft } = useAppSelector((state) => state.copilot);
  const gaps = useAppSelector((state) => state.investigation.payload.gaps);
  const [copied, setCopied] = useState(false);
  const openGaps = gaps.filter((gap) => gap.status === "open");

  const close = () => {
    dispatch(copilotActions.setEmailOpen(false));
    setCopied(false);
  };

  async function copy() {
    if (!emailDraft) return;
    try {
      await navigator.clipboard.writeText(emailDraft);
      setCopied(true);
      window.setTimeout(() => setCopied(false), 2000);
      dispatch(uiActions.pushToast({ kind: "success", title: "Email copied to the clipboard" }));
    } catch {
      dispatch(
        uiActions.pushToast({
          kind: "error",
          title: "Clipboard blocked",
          message: "Select the text and copy it manually.",
        }),
      );
    }
  }

  function download() {
    if (!emailDraft) return;
    const blob = new Blob([emailDraft], { type: "message/rfc822" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = "evidence-request.eml";
    document.body.appendChild(link);
    link.click();
    link.remove();
    URL.revokeObjectURL(url);
    dispatch(uiActions.pushToast({ kind: "success", title: "Downloaded evidence-request.eml" }));
  }

  return (
    <Modal
      open={emailOpen}
      onClose={close}
      title="Evidence request email"
      subtitle={`Drafted from ${openGaps.length} open evidence gap${openGaps.length === 1 ? "" : "s"} — review before sending.`}
      width="max-w-2xl"
    >
      <div className="overflow-hidden rounded-xl border border-ink-200">
        <div className="flex items-center justify-between border-b border-ink-100 bg-ink-50/60 px-3 py-2">
          <div className="flex items-center gap-2">
            <div className="grid h-6 w-6 place-items-center rounded-md bg-white text-ink-500 shadow-sm">
              <Mail className="h-3.5 w-3.5" />
            </div>
            <div>
              <div className="text-[11px] font-medium text-ink-800">To: QC records &amp; maintenance</div>
              <div className="text-[9.5px] text-ink-400">Generated by the copilot · not sent automatically</div>
            </div>
          </div>
          <span className="badge border-ai-200 bg-ai-50 text-ai-700">AI draft</span>
        </div>
        <pre className="max-h-[330px] overflow-y-auto whitespace-pre-wrap px-3.5 py-3 font-sans text-[11.5px] leading-relaxed text-ink-700">
          {emailDraft}
        </pre>
      </div>

      <div className="mt-3 flex items-center justify-between gap-3">
        <p className="max-w-sm text-[9.5px] leading-snug text-ink-400">
          The draft lists what is missing, why it matters and who should provide it. Quote the investigation code
          in your reply so records can be filed against the investigation.
        </p>
        <div className="flex shrink-0 items-center gap-2">
          <button className="btn btn-secondary btn-sm" onClick={download}>
            <Download className="h-3 w-3" />
            .eml
          </button>
          <button className="btn btn-secondary btn-sm" onClick={close}>
            Close
          </button>
          <button className="btn btn-primary btn-sm" onClick={() => void copy()}>
            {copied ? <Check className="h-3 w-3" /> : <Copy className="h-3 w-3" />}
            {copied ? "Copied" : "Copy email"}
          </button>
        </div>
      </div>

      <div className="mt-3 flex items-center gap-1.5 rounded-lg border border-ink-200 bg-ink-50/50 px-2.5 py-2 text-[9.5px] text-ink-500">
        <Send className="h-3 w-3 text-ink-400" />
        Outbound email is intentionally not automated in this demo. Copy the draft into your mail client.
      </div>
    </Modal>
  );
}
